import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const svgSourcePath = path.join(rootDir, 'public', 'upsed.svg');
const targetComponentPath = path.join(rootDir, 'src', 'components', 'UpsedLogo.tsx');

export function generateLogoComponent() {
  if (!fs.existsSync(svgSourcePath)) {
    console.warn(`[sync-logo] Source SVG not found at ${svgSourcePath}`);
    return;
  }

  const rawSvg = fs.readFileSync(svgSourcePath, 'utf-8');

  // Extract viewBox
  const viewBoxMatch = rawSvg.match(/viewBox="([^"]+)"/);
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : '0 0 854 378';

  // Extract inner SVG content (inside <svg ...> ... </svg>)
  const innerMatch = rawSvg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
  if (!innerMatch) {
    console.warn('[sync-logo] Failed to parse SVG inner content');
    return;
  }

  let content = innerMatch[1].trim();

  // Find all mask IDs in the SVG
  const maskIdRegex = /<mask\s+[^>]*id="([^"]+)"/g;
  const maskIds = [];
  let match;
  while ((match = maskIdRegex.exec(content)) !== null) {
    maskIds.push(match[1]);
  }

  // Generate dynamic React useId mask bindings
  const maskBindings = maskIds.map((id, index) => ({
    originalId: id,
    varName: `maskId_${index}`,
  }));

  // Replace mask IDs and mask url references with dynamic variables
  maskBindings.forEach(({ originalId, varName }) => {
    // Replace declaration: id="..." with id={maskId_X}
    content = content.replaceAll(
      new RegExp(`id="${originalId}"`, 'g'),
      `id={${varName}}`
    );
    // Replace reference: mask="url(#...)" with mask={`url(#\${maskId_X})`}
    content = content.replaceAll(
      new RegExp(`mask="url\\(#${originalId}\\)"`, 'g'),
      `mask={\`url(#\${${varName}})\`}`
    );
  });

  // Replace fill="white" or fill="#0f172a" or fill="#fff" with fill="currentColor"
  // ONLY for tags outside <mask ...>...</mask>
  content = content.replace(
    /(<mask[\s\S]*?<\/mask>)|(<path[^>]*?)fill="(?:white|#0f172a|#ffffff|#fff)"/gi,
    (m, maskBlock, pathPrefix) => {
      if (maskBlock) return maskBlock; // preserve rect fill="white" inside mask
      return `${pathPrefix}fill="currentColor"`;
    }
  );

  const maskCodeDeclarations = maskBindings.length > 0
    ? `  const rawId = useId();\n  const safeId = rawId.replace(/[^a-zA-Z0-9_-]/g, '_');\n` +
      maskBindings.map((b) => `  const ${b.varName} = \`${b.varName}-\${safeId}\`;`).join('\n')
    : '';

  const componentSource = `/* Auto-generated by scripts/generate-logo.js — DO NOT EDIT MANUALLY */
import React, { useId } from 'react';

export type LogoSize = 'xs' | 'sm' | 'md' | 'lg' | 'xl';

interface UpsedLogoProps {
  className?: string;
  size?: LogoSize;
  showTagline?: boolean;
}

const SIZES: Record<LogoSize, number> = {
  xs: 16,
  sm: 20,
  md: 24,
  lg: 36,
  xl: 48,
};

export const UpsedLogo: React.FC<UpsedLogoProps> = ({
  className = '',
  size = 'md',
  showTagline = false,
}) => {
  const height = SIZES[size] || SIZES.md;
${maskCodeDeclarations}

  return (
    <div className={\`inline-flex flex-col select-none leading-none \${className}\`}>
      <svg
        height={height}
        viewBox="${viewBox}"
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className="shrink-0"
        aria-label="UPSED"
        role="img"
        style={{ height, width: 'auto' }}
      >
        ${content}
      </svg>
      {showTagline && (
        <span className="text-[10px] text-slate-500 font-mono tracking-wider uppercase mt-1">
          UPS Native Core
        </span>
      )}
    </div>
  );
};

export default UpsedLogo;
`;

  fs.writeFileSync(targetComponentPath, componentSource, 'utf-8');
  console.log(`[sync-logo] Successfully regenerated ${targetComponentPath} from ${svgSourcePath}`);
}

// Run directly if invoked as a script
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateLogoComponent();
}

